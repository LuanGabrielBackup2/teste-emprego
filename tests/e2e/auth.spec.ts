import { expect, test } from '@playwright/test'

test('valida campos e mostra credenciais inválidas acessivelmente', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByText('Informe seu e-mail.')).toBeVisible()
  await expect(page.getByText('Informe sua senha.')).toBeVisible()
  await page.getByLabel('E-mail').fill('maya@jungle.test')
  await page.getByLabel('Senha').fill('incorreta')
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('alert')).toContainText('E-mail ou senha incorretos.')
})

test('login recupera sessão após refresh e permite logout', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('E-mail').fill('maya@jungle.test')
  await page.getByLabel('Senha').fill('Jungle#2025')
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page).toHaveURL(/127\.0\.0\.1:4173\/(\?.*)?$/)
  await expect(page.getByRole('button', { name: 'Sair da conta de Maya Silva' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Sair da conta de Maya Silva' })).toBeVisible()
  await page.getByRole('button', { name: 'Sair da conta de Maya Silva' }).click()
  await expect(page.getByRole('link', { name: 'Entrar' })).toBeVisible()
  await expect(page.evaluate(() => localStorage.getItem('jungle-market.session.v1'))).resolves.toBeNull()
})

