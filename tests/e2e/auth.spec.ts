test('mescla carrinho visitante sem duplicar e isola dados por usuário', async ({ page }) => {
  test.setTimeout(60_000)
  await page.goto('/')
  const guestCard = page.locator('.nft-card').filter({ hasText: 'Emerald Ape #042' })
  await guestCard.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await expect(guestCard.getByRole('status')).toHaveText('Item adicionado ao carrinho.')
  await expect(page.getByRole('link', { name: 'Carrinho, 1 item' })).toBeVisible()
  await page.goto('/checkout')
  await page.getByLabel('E-mail').fill('maya@jungle.test')
  await page.getByLabel('Senha').fill('Jungle#2025')
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('link', { name: 'Carrinho, 1 item' })).toBeVisible()
  await page.getByRole('link', { name: 'Carrinho, 1 item' }).click()
  await expect(page.getByRole('heading', { name: 'Emerald Ape #042' })).toBeVisible()
  await expect(page.locator('.cart-grand-total')).toContainText('R$ 235,90')
  const mergeResult = await page.evaluate(async () => {
    const carts = JSON.parse(localStorage.getItem('jungle-market.cart.v1')!)
    const session = JSON.parse(localStorage.getItem('jungle-market.session.v1')!)
    carts.guest.lines = [{ nftId: 'emerald-ape-042', quantity: 2 }]
    localStorage.setItem('jungle-market.cart.v1', JSON.stringify(carts))
    const response = await fetch('/api/cart/merge-guest', { method: 'POST', headers: { Authorization: `Bearer ${session.token}` } })
    return { status: response.status, cart: await response.json() }
  })
  expect(mergeResult.status).toBe(200)
  expect(mergeResult.cart.items).toHaveLength(1)
  expect(mergeResult.cart.items[0].quantity).toBe(3)
  expect(mergeResult.cart.quote.totalBRL).toBe('707.70')
  await page.getByRole('button', { name: 'Sair da conta de Maya Silva' }).click()
  await page.goto('/login')
  await page.getByLabel('E-mail').fill('noah@jungle.test')
  await page.getByLabel('Senha').fill('Canopy#2025')
  await page.getByRole('button', { name: 'Entrar' }).click()
  await page.goto('/cart')
  await expect(page.getByTestId('cart-empty')).toBeVisible()
})

